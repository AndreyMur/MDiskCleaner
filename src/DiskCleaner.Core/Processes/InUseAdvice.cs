namespace DiskCleaner.Core.Processes;

/// <summary>
/// Рекомендуемая стратегия для объекта, помеченного <c>IN_USE</c> (FR-5.8): какой статус
/// показать пользователю — «закройте приложение и повторите» либо «отложить шаг».
/// </summary>
public enum InUseAdvice
{
    /// <summary>Объект использует «долгоживущее» приложение (VS Code, браузер) — рекомендуем закрыть и повторить.</summary>
    CloseAndRetry,

    /// <summary>Объект занят фоновым/служебным процессом — шаг откладывается, повторить позже.</summary>
    DeferStep
}
