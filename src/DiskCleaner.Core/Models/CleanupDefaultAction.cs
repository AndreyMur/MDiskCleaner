namespace DiskCleaner.Core.Models;

/// <summary>
/// Действие по умолчанию для объекта очистки (FR-1.6): как объект должен
/// обрабатываться без явного выбора пользователя.
/// </summary>
public enum CleanupDefaultAction
{
    /// <summary>Очистить без дополнительного подтверждения (низкий риск).</summary>
    Clean,

    /// <summary>Спросить подтверждение перед очисткой (средний риск).</summary>
    Ask,

    /// <summary>Не трогать и не предлагать к автоудалению (высокий риск / используется).</summary>
    Keep
}
